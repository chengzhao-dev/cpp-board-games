#!/usr/bin/env bash
#===------------------------------------------------------------------------===#
# build-and-run.sh - 棋盘状态工程的一键验证脚本
#
# 依次完成：CMake 配置（每次幂等重跑）→ 编译 → CTest → 运行程序。
# 测试与运行步骤用临时 LD_LIBRARY_PATH 加固动态库查找，不改动系统配置。
# 在 WSL Ubuntu 中于本目录执行：./build-and-run.sh
#===------------------------------------------------------------------------===#

set -euo pipefail

cd "$(dirname "$0")"

#===------------------------------------------------------------------------===#
# 输出辅助
#===------------------------------------------------------------------------===#

# 打印步骤标题，空行用于分隔连续步骤。
# Arguments: 步骤标题文本（如 "1. 配置"）
# Outputs:   空行 + 一行 "==> 标题" 到 stdout
header() {
  printf '\n==> %s\n' "$*"
}

# 将错误提示写到 stderr，避免混入正常输出。
# Arguments: 错误描述
# Outputs:   一行 "错误: 描述" 到 stderr
err() {
  printf '错误: %s\n' "$*" >&2
}

# 失败时补充定位提示，并保留原命令的非零退出码。
trap 'err "构建流程失败，定位最靠近上方的失败命令后重试"' ERR

#===------------------------------------------------------------------------===#
# 1. 配置
#===------------------------------------------------------------------------===#

header "1. 配置"

# 每次重新配置，使脚本里的参数进入当前构建计划。
cmake -S . -B build -G Ninja \
  -DCMAKE_BUILD_TYPE=Debug \
  -DCMAKE_CXX_COMPILER=clang++ \
  -DCMAKE_EXPORT_COMPILE_COMMANDS=ON

#===------------------------------------------------------------------------===#
# 2. 编译
#===------------------------------------------------------------------------===#

header "2. 编译"
cmake --build build

#===------------------------------------------------------------------------===#
# 3. 测试
#===------------------------------------------------------------------------===#

header "3. 测试"

# 只包住这条命令的库查找路径：主路径是可执行文件内的 RPATH，这里仅加固。
# 变量展开保留调用者已有的 LD_LIBRARY_PATH，命令结束即失效。
env LD_LIBRARY_PATH="$PWD/build/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" \
  ctest --test-dir build --output-on-failure

#===------------------------------------------------------------------------===#
# 4. 运行
#===------------------------------------------------------------------------===#

header "4. 运行"

# 同样的临时加固：不写入 bashrc、系统 PATH 或 ldconfig。
env LD_LIBRARY_PATH="$PWD/build/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" \
  ./build/bin/tic_tac_toe_cli
