#!/usr/bin/env bash
#===------------------------------------------------------------------------===#
# build-and-run.sh - 最小工程的一键验证脚本
#
# 依次完成：CMake 配置（每次幂等重跑）→ 编译 → CTest → 运行程序。
# 在 WSL Ubuntu 中于本目录执行：./build-and-run.sh
#===------------------------------------------------------------------------===#

set -euo pipefail

cd "$(dirname "$0")"

#===------------------------------------------------------------------------===#
# 输出辅助
#===------------------------------------------------------------------------===#

# 打印步骤标题，空行用于分隔连续步骤。
# Arguments: 步骤标题文本（如 "1. 配置"）
# Outputs:   空行 + 一行 "==> 标题" 到 stdout
header() {
  printf '\n==> %s\n' "$*"
}

# 将错误提示写到 stderr，避免混入正常输出。
# Arguments: 错误描述
# Outputs:   一行 "错误: 描述" 到 stderr
err() {
  printf '错误: %s\n' "$*" >&2
}

# 失败时补充定位提示，并保留原命令的非零退出码。
trap 'err "构建流程失败，定位最靠近上方的失败命令后重试"' ERR

#===------------------------------------------------------------------------===#
# 1. 配置
#===------------------------------------------------------------------------===#

header "1. 配置"

# 每次重新配置，使脚本里的参数进入当前构建计划。
cmake -S . -B build -G Ninja \
  -DCMAKE_BUILD_TYPE=Debug \
  -DCMAKE_CXX_COMPILER=clang++ \
  -DCMAKE_EXPORT_COMPILE_COMMANDS=ON

#===------------------------------------------------------------------------===#
# 2. 编译
#===------------------------------------------------------------------------===#

header "2. 编译"
cmake --build build

#===------------------------------------------------------------------------===#
# 3. 测试
#===------------------------------------------------------------------------===#

header "3. 测试"
ctest --test-dir build --output-on-failure

#===------------------------------------------------------------------------===#
# 4. 运行
#===------------------------------------------------------------------------===#

header "4. 运行"
./build/bin/tic_tac_toe_cli
